#!/bin/zsh
setopt err_exit no_unset pipe_fail

# Lock GitHub Actions with a workflow lockfile, per:
# https://hugovk.dev/blog/2026/lock-github-actions/
#
# Requires: gh extension install github/gh-actions-lock

git diff --exit-code
git switch main
git pull

workflow=.github/workflows/main.yml

if [[ ! -f $workflow ]]; then
    echo "No $workflow found."
    exit 0
fi

if [[ -f .github/workflows/actions.lock ]]; then
    echo "Already using an actions lockfile."
    exit 0
fi

lock_version=$(gh release view --repo github/gh-actions-lock --json tagName --jq .tagName)

git switch -c lock_github_actions

# Add a job to verify the lockfile, before the release job if there is one.
# (f) splits the file into lines, (M) keeps the elements matching the pattern
# rather than removing them, and ## strips the longest matching prefix.
content=$(<$workflow)
checkout=${${(M)${(f)content}:#*uses: actions/checkout@*}[1]##*uses: }

job="  lockfile:
    name: Verify actions lockfile
    runs-on: ubuntu-slim
    env:
      GH_TOKEN: \${{ github.token }}

    steps:
    - uses: $checkout
      with:
        persist-credentials: false

    - run: gh extension install github/gh-actions-lock --pin $lock_version

    - run: gh actions-lock --verify
"

if [[ $content == *$'\n  release:'* ]]; then
    content=${content/$'\n  release:'/$'\n'$job$'\n  release:'}
else
    content+=$'\n\n'$job
fi
print -r -- $content > $workflow

# Replace hash pins with tags and write .github/workflows/actions.lock
gh actions-lock

# zizmor only supports lockfiles from v1.32.0
if [[ -f .pre-commit-config.yaml ]] && rg -q zizmor-pre-commit .pre-commit-config.yaml; then
    pre-commit autoupdate --freeze --repo https://github.com/zizmorcore/zizmor-pre-commit
    git add .pre-commit-config.yaml
fi

git add .github/workflows
git commit -m "Lock GitHub Actions

Use a [workflow lockfile](https://docs.github.com/en/actions/concepts/security/workflow-dependency-lockfiles), generated by [gh-actions-lock](https://github.com/github/gh-actions-lock), and verify it in CI."

git push
gh pr create --fill
sleep 1
gh pr merge --squash --delete-branch --auto
